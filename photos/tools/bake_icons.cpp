#include <stdio.h>

#include "iconshapes.h"

int main()
    {
    const TInt scale = 256;
    static TUint8 pixels[EIconCount][64 * 1024];
    TUint32 offsets[EIconCount];
    TUint32 total = 0;
    TSize sizes[EIconCount];
    for (TInt i = 0; i < EIconCount; i++)
        {
        sizes[i] = IconShapes::PixelSize((TIconId)i, scale);
        const TInt stride = (sizes[i].iWidth * 2 + 3) & ~3;
        IconShapes::Render((TIconId)i, scale, pixels[i], stride);
        offsets[i] = total;
        total += stride * sizes[i].iHeight;
        }
    printf("// Generated by tools/bake-icons.sh from src/iconshapes.cpp at scale %d: do not edit.\n", scale);
    printf("#include \"iconbake.h\"\n\nconst TInt KBakedScale = %d;\n\n", scale);
    printf("const TUint16 KBakedSizes[EIconCount][2] =\n    {\n");
    for (TInt i = 0; i < EIconCount; i++)
        printf("    { %d, %d },\n", sizes[i].iWidth, sizes[i].iHeight);
    printf("    };\n\nconst TUint32 KBakedOffsets[EIconCount] =\n    {\n   ");
    for (TInt i = 0; i < EIconCount; i++)
        printf(" %u,", offsets[i]);
    printf("\n    };\n\nconst TUint8 KBakedPixels[%u] =\n    {\n", total);
    TInt column = 0;
    for (TInt i = 0; i < EIconCount; i++)
        {
        const TInt stride = (sizes[i].iWidth * 2 + 3) & ~3;
        for (TInt b = 0; b < stride * sizes[i].iHeight; b++)
            {
            if (column == 0)
                printf("   ");
            printf(" %u,", pixels[i][b]);
            if (++column == 24)
                {
                printf("\n");
                column = 0;
                }
            }
        }
    printf("%s    };\n", column ? "\n" : "");
    fprintf(stderr, "baked %d icons, %u bytes\n", (int)EIconCount, total);
    return 0;
    }
